    /** Habilita solo el campo específico de la subclase seleccionada. */
    private void actualizarCamposPorTipo() {
        String tipo = (String) cmbTipo.getSelectedItem();
        habilitar(lblPaginas, txtPaginas, "Libro".equals(tipo));
        habilitar(lblEdicion, txtEdicion, "Revista".equals(tipo));
        habilitar(lblConferencia, txtConferencia, "Articulo".equals(tipo));
    }

    private void habilitar(javax.swing.JLabel etiqueta, JTextField campo, boolean activo) {
        etiqueta.setEnabled(activo);
        campo.setEnabled(activo);
        if (!activo) {
            campo.setText("");
        }
    }

    /** Lee el formulario e instancia la subclase adecuada (polimorfismo). */
    private Trabajo crearTrabajoDesdeFormulario() throws DatoInvalido {
        String titulo = leerTexto(txtTitulo, "Título");
        if (lista.buscarPorTitulo(titulo) != null) {
            throw new DatoInvalido("Ya existe un trabajo con el título \"" + titulo + "\".", txtTitulo);
        }
        String autor = leerTexto(txtAutor, "Autor");
        int anio = leerEnteroPositivo(txtAnio, "Año de publicación");
        int anioActual = Year.now().getValue();
        if (anio > anioActual) {
            throw new DatoInvalido("El año de publicación no puede ser mayor a " + anioActual + ".", txtAnio);
        }
        switch ((String) cmbTipo.getSelectedItem()) {
            case "Libro":
                return new Libro(titulo, autor, anio, leerEnteroPositivo(txtPaginas, "Número de páginas"));
            case "Revista":
                return new Revista(titulo, autor, anio, leerEnteroPositivo(txtEdicion, "Número de edición"));
            default:
                return new Articulo(titulo, autor, anio, leerTexto(txtConferencia, "Nombre de conferencia"));
        }
    }

    private String leerTexto(JTextField campo, String nombre) throws DatoInvalido {
        String valor = campo.getText().trim();
        if (valor.isEmpty()) {
            throw new DatoInvalido("El campo \"" + nombre + "\" no puede estar vacío.", campo);
        }
        return valor;
    }

    private int leerEnteroPositivo(JTextField campo, String nombre) throws DatoInvalido {
        String texto = campo.getText().trim();
        if (texto.isEmpty()) {
            throw new DatoInvalido("El campo \"" + nombre + "\" no puede estar vacío.", campo);
        }
        try {
            int valor = Integer.parseInt(texto);
            if (valor <= 0) {
                throw new DatoInvalido("\"" + nombre + "\" debe ser un entero mayor a cero.", campo);
            }
            return valor;
        } catch (NumberFormatException e) {
            throw new DatoInvalido("\"" + nombre + "\" debe ser un número entero válido.", campo);
        }
    }

    /** Posición basada en 0; debe quedar entre 0 y maximo (inclusive). */
    private int leerPosicion(int maximo, String operacion) throws DatoInvalido {
        String texto = txtPosicion.getText().trim();
        if (texto.isEmpty()) {
            throw new DatoInvalido("Escribe la posición donde deseas " + operacion + ".", txtPosicion);
        }
        int pos;
        try {
            pos = Integer.parseInt(texto);
        } catch (NumberFormatException e) {
            throw new DatoInvalido("La posición debe ser un número entero válido.", txtPosicion);
        }
        if (pos < 0 || pos > maximo) {
            throw new DatoInvalido("Posición fuera de rango para " + operacion
                    + ": debe estar entre 0 y " + maximo + ".", txtPosicion);
        }
        return pos;
    }

    private void verificarNoVacia(String operacion) throws DatoInvalido {
        if (lista.isEmpty()) {
            throw new DatoInvalido("No se puede " + operacion + ": la lista circular está vacía.", null);
        }
    }

    private void terminarInsercion(Trabajo t, String donde) {
        actualizarVista();
        limpiarCampos();
        estado("Insertado " + donde + ": " + t.getTitulo() + " (" + t.getTipo() + ") · "
                + lista.getTamanio() + " nodos.");
    }

    /** Refresca el dibujo, la secuencia completa y el trabajo actual. */
    private void actualizarVista() {
        txtSecuencia.setText(lista.mostrarTodos());
        txtSecuencia.setCaretPosition(0);
        panelCircular.setDatos(lista.aLista(), lista.getIndiceActual());
        if (lista.isEmpty()) {
            txtActual.setText("(sin elementos) Agrega un trabajo para comenzar a navegar.");
        } else {
            int idx = lista.getIndiceActual();
            txtActual.setText("Posición " + idx + " de " + (lista.getTamanio() - 1)
                    + (idx == 0 ? "   «CABEZA»" : "") + "\n" + lista.consultarActual());
        }
        txtActual.setCaretPosition(0);
    }

    private void limpiarCampos() {
        txtTitulo.setText("");
        txtAutor.setText("");
        txtAnio.setText("");
        txtPaginas.setText("");
        txtEdicion.setText("");
        txtConferencia.setText("");
        txtTitulo.requestFocusInWindow();
    }

    private void estado(String mensaje) {
        lblEstado.setText(mensaje);
    }

    /** Ejecuta una acción mostrando cualquier error de validación en un cuadro de diálogo. */
    private void ejecutar(Accion accion) {
        try {
            accion.ejecutar();
        } catch (DatoInvalido e) {
            mostrarError(e.getMessage());
            if (e.campo != null) {
                e.campo.requestFocusInWindow();
                if (e.campo instanceof JTextField) {
                    ((JTextField) e.campo).selectAll();
                }
            }
        } catch (IllegalStateException | IndexOutOfBoundsException | IllegalArgumentException e) {
            // Protección de la propia lista (lista vacía, rango, datos inválidos)
            mostrarError(e.getMessage());
        }
    }

    private void mostrarError(String mensaje) {
        estado("⚠ " + mensaje);
        JOptionPane.showMessageDialog(this, mensaje, "Validación", JOptionPane.WARNING_MESSAGE);
    }

    @FunctionalInterface
    private interface Accion {
        void ejecutar() throws DatoInvalido;
    }

    /** Error de validación del formulario; recuerda qué campo hay que corregir. */
    private static class DatoInvalido extends Exception {

        final JComponent campo;

        DatoInvalido(String mensaje, JComponent campo) {
            super(mensaje);
            this.campo = campo;
        }
    }

