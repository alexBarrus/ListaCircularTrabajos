    private void btnEliminarPosicionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarPosicionActionPerformed
        ejecutar(() -> {
            verificarNoVacia("eliminar");
            int pos = leerPosicion(lista.getTamanio() - 1, "eliminar");
            Trabajo eliminado = lista.eliminar(pos);
            actualizarVista();
            estado("Eliminado de la posición " + pos + ": " + eliminado.getTitulo()
                    + " · el ciclo se reenlazó (" + lista.getTamanio() + " nodos).");
        });
    }//GEN-LAST:event_btnEliminarPosicionActionPerformed

    private void btnEliminarTituloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarTituloActionPerformed
        ejecutar(() -> {
            verificarNoVacia("eliminar");
            String titulo = leerTexto(txtTitulo, "Título (a eliminar)");
            Trabajo eliminado = lista.eliminarPorTitulo(titulo);
            if (eliminado == null) {
                throw new DatoInvalido("No existe ningún trabajo con el título \"" + titulo + "\".", txtTitulo);
            }
            actualizarVista();
            estado("Eliminado por título: " + eliminado.getTitulo()
                    + " · el ciclo se reenlazó (" + lista.getTamanio() + " nodos).");
        });
    }//GEN-LAST:event_btnEliminarTituloActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        ejecutar(() -> {
            verificarNoVacia("buscar");
            String titulo = leerTexto(txtTitulo, "Título (a buscar)");
            Trabajo t = lista.buscarPorTitulo(titulo);
            if (t == null) {
                throw new DatoInvalido("No existe ningún trabajo con el título \"" + titulo + "\".", txtTitulo);
            }
            int pos = lista.indiceDe(titulo);
            JOptionPane.showMessageDialog(this,
                    "Encontrado en la posición " + pos + ":\n\n" + t,
                    "Buscar por título", JOptionPane.INFORMATION_MESSAGE);
            estado("Búsqueda: \"" + t.getTitulo() + "\" está en la posición " + pos + ".");
        });
    }//GEN-LAST:event_btnBuscarActionPerformed

